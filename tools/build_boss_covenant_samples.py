"""Generate the planner's boss matchup counts from garrison-rl's published sp5 draw table.

Usage: python tools/build_boss_covenant_samples.py path/to/garrison-rl
The checkout must contain its matching Stronghold-Protocol data.
"""
import argparse
import json
from collections import Counter
from pathlib import Path


def load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def aggregate(rows, bosses, bonds):
    cells = Counter()
    for boss, main, _, cleared in rows:
        if cleared not in (0, 1):
            raise ValueError(f"Invalid clear flag {cleared}")
        key = bosses[boss]["name"], bonds[main]["name"]
        cells[key, "runs"] += 1
        cells[key, "clears"] += int(cleared)
    return {(boss, main): (cells[(boss, main), "clears"], count)
            for ((boss, main), metric), count in cells.items() if metric == "runs"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path)
    args = parser.parse_args()
    rows = load(args.checkout / "python/garrison_rl/tables/sp5_draw_final.json")["rows"]
    data = args.checkout / "Stronghold-Protocol/data/versions/act3autochess-v3_1"
    bosses, bonds = load(data / "bosses.json"), load(data / "bonds.json")
    lines = [
        "// Generated by tools/build_boss_covenant_samples.py from CarlosDJY/garrison-rl 405d328.",
        "// Cells contain simulated clears and runs. The source groups difficulty at level 16.",
        "namespace ASPAssistant.Core.Services;", "",
        "internal static class BossCovenantSamples", "{",
        "    internal static readonly Dictionary<(string Boss, bool High, string Covenant), (int Clears, int Runs)> Counts = new()",
        "    {",
    ]
    for tier in ("lo", "hi"):
        for (boss, core), (wins, total) in sorted(aggregate(rows[tier], bosses, bonds).items()):
            name = json.dumps(boss, ensure_ascii=False)
            covenant = json.dumps(core, ensure_ascii=False)
            high = "true" if tier == "hi" else "false"
            lines.append(f"        [({name}, {high}, {covenant})] = ({wins}, {total}),")
    output = Path(__file__).resolve().parents[1] / "src/ASPAssistant.Core/Services/BossCovenantSamples.g.cs"
    output.write_text("\n".join([*lines, "    };", "}", ""]), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
