import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [, , checkout, flag, version] = process.argv;
if (!checkout || flag !== '--version' || version !== 'act3autochess@V3_1') {
    throw new Error('Expected a Stronghold-Protocol checkout and --version act3autochess@V3_1');
}
const moduleUrl = path => pathToFileURL(resolve(checkout, path)).href;
await import(moduleUrl('tools/versions/runtime.mjs'));
const { Match } = await import(moduleUrl('server/match/Match.js'));
const { VirtualScheduler } = await import(moduleUrl('server/match/scheduler.js'));
const { getData } = await import(moduleUrl('server/data.js'));
const { buildNormalWave } = await import(moduleUrl('server/match/waves.js'));
const data = getData();
const profiles = JSON.parse(readFileSync(new URL('../data/operator_profiles.json', import.meta.url), 'utf8')).operators;
const scenarios = [[5, 89, '9,6'], [8, 311, '10,7'], [9, 619, '9,7'], [11, 947, '10,6']];

function meanDamage(id) {
    let total = 0;
    for (const [round, seed, cell] of scenarios) {
        const match = new Match({
            roomCode: 'CALIB', mode: 'solo', difficulty: '规程等级8', modeId: 'mode_single_8',
            seats: [{ seat: 0, playerId: 'p', name: 'p', isBot: true, connected: true }],
            seed, data, scheduler: new VirtualScheduler(), send() {}, broadcast() {}, onEnd() {},
            log: { warn() {}, info() {}, debug() {}, error(message) { throw Error(String(message)); } },
        });
        match.round = round;
        match.stageId = 'act3autochess_m03';
        match.stage = data.stages[match.stageId];
        match.wave = buildNormalWave(match.gd, match.rngWaves, match.factions, round);
        const player = match.players.get('p');
        const piece = player.newPiece('chess', id);
        piece.dir = 'RIGHT';
        player.board.set(cell, piece);
        player.recompute();
        match.dispatch(player, 'onPrepEnd', { round });
        const options = match._normalOpts(player, { preview: true });
        if (!options.spawns.length || options.players[0].units.length !== 1 || !match.deployMapFor(player).has(cell)) {
            throw Error(`Invalid calibration battle for ${id}, round ${round}`);
        }
        const battle = match.newBattle(options, { preview: true });
        while (!battle.finished) battle.step();
        total += battle.result().perPlayer.p.damageDealt;
    }
    return Math.round(total / scenarios.length);
}

const entries = Object.values(data.chess)
    .filter(piece => piece.visible && !piece.isGolden && Object.hasOwn(profiles, piece.name))
    .map(piece => `        [${JSON.stringify(piece.name)}] = (${meanDamage(piece.chessId)}, ${meanDamage(piece.goldenId)}),`)
    .sort();
if (!entries.length) throw Error('No operator profiles matched the simulator');
const output = `// Generated by tools/build_placement_samples.mjs. Values are mean damage from four solo waves.
namespace ASPAssistant.Core.Services;

internal static class PlacementDamageSamples
{
    internal static readonly Dictionary<string, (int Normal, int Elite)> ByName = new(StringComparer.Ordinal)
    {
${entries.join('\n')}
    };
}
`;
writeFileSync(new URL('../src/ASPAssistant.Core/Services/PlacementDamageSamples.g.cs', import.meta.url), output);
