// node tools/build_placement_waves.mjs <Stronghold-Protocol checkout> --version act3autochess@V3_1
// Fixed simulation at 9a41bbe98255. The assistant uses the resulting grid without a JS runtime.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [, , checkout, flag, version] = process.argv;
if (!checkout || flag !== '--version' || version !== 'act3autochess@V3_1') throw Error('Expected simulator checkout and --version act3autochess@V3_1');
const from = path => import(pathToFileURL(resolve(checkout, path)).href);
await from('tools/versions/runtime.mjs');
const { Match } = await from('server/match/Match.js');
const { VirtualScheduler } = await from('server/match/scheduler.js');
const { buildNormalWave } = await from('server/match/waves.js');
const { faRehearsalTicks } = await from('server/match/bot.js');
const { colliderKeys } = await from('server/sim/body.js');
const { COLS } = await from('server/sim/constants.js');
const { getData } = await from('server/data.js');
const data = getData();
const stages = { desert_crates: 1, desert_cactus: 2, desert_steel: 3, desert_laser: 4, city: 5, desert_camo: 6,
    snow: 9, palace: 10, snow_ice: 11, palace_arrows: 12 };
const width = 21, height = 9, count = width * height;

function trace(stage, round, seed, boss) {
    const m = new Match({roomCode:'WAVE', mode:'solo', difficulty:'规程等级8', modeId:'mode_single_8',
        seats:[{seat:0, playerId:'p', name:'p', isBot:true, connected:true}], seed, data, scheduler:new VirtualScheduler(),
        send(){}, broadcast(){}, onEnd(){}, log:{warn(){}, info(){}, debug(){}, error(message){ throw Error(String(message)); }}});
    const player = m.players.get('p');
    m.round = round;
    m.stageId = stage;
    m.stage = data.stages[stage];
    let battle;
    if (boss) {
        m._planBossWaves();
        m.startFinalAssault(round === m.gd.hiddenRound);
        battle = m.fields[0].battle;
    } else {
        m.wave = buildNormalWave(m.gd, m.rngWaves, m.factions, round);
        battle = m.newBattle(m._normalOpts(player, {preview:true}), {preview:true});
    }
    const weights = new Float64Array(count);
    const ticks = boss ? faRehearsalTicks(m) : 12000;
    for (let i = 0; i < ticks && !battle.finished; i++) {
        battle.step();
        if (i % 15 !== 0) continue;
        for (const enemy of battle.enemies) {
            if (!enemy.alive || boss && !enemy.bossPool) continue;
            const body = colliderKeys(enemy);
            for (const key of body) {
                // Local grid covers rows -2..6 and columns -3..17. Boss rows are 7 below board rows.
                const y = (boss ? 7 : 14) - Math.floor(key / COLS);
                if (y >= 0 && y < height) weights[y * width + key % COLS] += 1 / body.length;
            }
        }
    }
    if (!boss && !battle.finished) throw Error('Wave timeout: ' + stage + '/' + round);
    return weights;
}

function encode(values) {
    const peak = Math.max(...values);
    if (!peak) throw Error('Empty wave footprint');
    return Buffer.from(values.map(v => Math.round(v * 255 / peak))).toString('base64');
}

const rows = [];
for (const [map, id] of Object.entries(stages)) {
    const stage = 'act3autochess_m' + String(id).padStart(2, '0');
    const average = new Float64Array(count);
    const rounds = [];
    for (let round = 1; round <= 15; round++) {
        const boss = round >= 14;
        const total = new Float64Array(count);
        for (let trial = 0; trial < (boss ? 24 : 6); trial++) {
            const values = trace(stage, round, 3119 + trial * 127, boss);
            const mass = values.reduce((a,b) => a+b, 0);
            if (mass > 0) for (let i = 0; i < count; i++) total[i] += values[i] / mass;
        }
        if (!boss) for (let i = 0; i < count; i++) average[i] += total[i];
        rounds.push(encode(total));
    }
    rows.push('        ["' + map + '"] = [\n' + [encode(average), ...rounds].map(s => '            Decode("' + s + '"),').join('\n') + '\n        ],');
}
writeFileSync(new URL('../src/ASPAssistant.Core/Services/PlacementWaveSamples.g.cs', import.meta.url),
    '// Generated by tools/build_placement_waves.mjs; 0 = average, 1..13 = normal, 14 = boss, 15 = hidden boss.\n' +
    'namespace ASPAssistant.Core.Services;\n\ninternal static class PlacementWaveSamples\n{\n' +
    '    private static byte[] Decode(string text) => Convert.FromBase64String(text);\n' +
    '    internal static readonly Dictionary<string, byte[][]> ByMap = new(StringComparer.Ordinal)\n    {\n' +
    rows.join('\n') + '\n    };\n}\n');
